# score DEFECT CASE WANT_KIND WANT_TEXT: a run generated with one defect in one case; that case's line must carry the
# verdict and the text, and the run's exit must not be 0.
score() {
  local defect="$1" case="$2" kind="$3" text="$4" run="$work/run-$1-$2" out rc line
  python3 hack/test/restart-session/make_fixture.py "$run" "$defect" "$case" || { bad "$defect: the fixture was not built"; return; }
  out="$(python3 experiments/distributed-restart/score_eks.py "$run" 2>&1)"
  rc=$?
  line="$(grep -E "^[A-Z]+ +${case}[: ]" <<<"$out" | head -1)"
  if [[ "$kind" == ACCEPTED ]]; then
    if [[ "$line" == "ACCEPTED $case "* && "$line" == *"$text"* && $rc == 0 ]]; then ok "$defect: still accepted, $text"; else bad "$defect: $line (exit $rc)"; fi
  elif [[ "$line" == "$kind"*"$case: "*"$text"* && $rc != 0 ]]; then
    ok "$defect: $(cut -c1-160 <<<"$line")"
  else
    bad "$defect on $case: want $kind '$text', got '$line' (exit $rc)"
  fi
}

