#!/usr/bin/env bash
#
# The distributed restart paid session (TRAIN=restart), rehearsed with no cluster, no card and no credentials.
#
#   bash hack/test/check-restart-session.sh
#
# Three parts, each against the real files:
#   1. hack/eks-gitops-session.sh with TRAIN=restart, run from a throwaway commit of what it reads, against stub aws,
#      terraform, kubectl, helm and gh: every refusal stops it before `terraform init` and before the kill switch, and
#      a run that passes every refusal has logged the terraform variables the watchdog's destroy is built from.
#   2. hack/lib/restart-session.sh's functions against stubs answering from per-case scripts: the termination fences
#      only on EC2's `terminated`, the job and volume it renders, the fault window, the clock probe, the retirement
#      that does not read an error as "gone", and the GPU deadline.
#   3. experiments/distributed-restart/score_eks.py over runs generated by hack/test/restart-session/make_fixture.py
#      from the producers' own line shapes: a clean run is accepted, and each defect is refused with its reason.
#
# What this does not show: the case procedure (restart_run_case) against a cluster, controller, NFS or GPU; nothing
# here runs it end to end.
set -uo pipefail
cd "$(dirname "$0")/../.." || exit 1

fails=0
ok() { echo "ok: $*"; }
bad() {
  echo "FAIL: $*"
  fails=$((fails + 1))
}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

mkdir -p "$work/bin" "$work/rules"
# The stub records every call and answers from $STUB_RULES/<tool>.sh when that exists, else from the defaults below.
cat >"$work/bin/stub" <<'EOF'
#!/usr/bin/env bash
tool=$(basename "$0")
printf '%s %s\n' "$tool" "$*" >>"${STUB_CALLS:?the stub was given nowhere to record its calls}" || exit 98
if [[ -n "${STUB_RULES:-}" && -f "$STUB_RULES/$tool.sh" ]]; then
  # shellcheck disable=SC1090
  . "$STUB_RULES/$tool.sh" "$@"
  exit $?
fi
case "$tool $*" in
  "aws configure export-credentials"*)
    if [[ -n "${STUB_CRED_NOEXP:-}" ]]; then echo '{"Version": 1, "AccessKeyId": "AKIA"}'; exit 0; fi
    # A fresh SSO credential lasts the permission set's SessionDuration, PT12H, so 720 minutes is the most any stub may claim.
    printf '{"Version": 1, "AccessKeyId": "ASIA", "Expiration": "%s"}\n' "$(date -u -d "+${STUB_CRED_MIN:-720} minutes" +%Y-%m-%dT%H:%M:%SZ)" ;;
  "aws eks describe-cluster"*)
    echo "An error occurred (ResourceNotFoundException) when calling the DescribeCluster operation: No cluster found" >&2
    exit 254 ;;
  "aws service-quotas get-service-quota"*) echo "${STUB_QUOTA:-128.0}" ;;
  "aws ec2 describe-instances"*) echo "${STUB_RUNNING:-[]}" ;;
  "aws ec2 describe-instance-types"*) echo '[["g5.xlarge", 4], ["g5.12xlarge", 48]]' ;;
  "aws pricing get-products"*)
    python3 -c '
import json, sys
p = {"terms": {"OnDemand": {"t": {"priceDimensions": {"d": {"unit": "Hrs", "pricePerUnit": {"USD": sys.argv[1]}}}}}}}
print(json.dumps({"PriceList": [json.dumps(p)]}))' "${STUB_PRICE:-1.2370000000}" ;;
  "gh "*) echo "stub gh refuses, so a case that passes every refusal stops here" >&2; exit 1 ;;
  "kubectl version"* | "helm version"* | "terraform version"* | "aws --version"*) echo "stub" ;;
  "terraform "*) echo "terraform reached" >&2; exit 1 ;;
  *) exit 0 ;;
esac
EOF
chmod +x "$work/bin/stub"
for t in aws terraform kubectl helm gh; do ln -s stub "$work/bin/$t"; done

# --- 1. the session's refusals ------------------------------------------------------------------------------------
# A copy holding only what the session reads before Terraform, committed, because a dirty tree is one of the refusals;
# it has no bin/, which the session puts ahead of PATH and which would otherwise answer in the stubs' place.
repo="$work/repo"
mkdir -p "$repo/hack/lib" "$repo/experiments/distributed-restart" "$repo/experiments/cpu-ddp" "$repo/experiments/multi-gpu-throughput"
cp hack/eks-gitops-session.sh "$repo/hack/"
cp hack/lib/train-session.sh hack/lib/ddp-arms.sh hack/lib/gpu-ttl.sh hack/lib/gpu-fault.sh hack/lib/restart-session.sh \
  hack/lib/allreduce-arms.sh "$repo/hack/lib/"
cp experiments/distributed-restart/train.py "$repo/experiments/distributed-restart/"
cp experiments/cpu-ddp/train.py "$repo/experiments/cpu-ddp/"
(cd "$repo" && git init -q && git add -A && git -c user.name=check -c user.email=check@example.invalid commit -qm fixture) ||
  { echo "FAIL: could not commit the session's copy"; exit 1; }
sha="$(sha256sum experiments/distributed-restart/train.py | cut -d' ' -f1)"

# session NAME WANT [VAR=VALUE...]: TRAIN=restart with the given environment exits non-zero, prints WANT, and never
# reached Terraform or the kill switch.
session() {
  local name="$1" want="$2" out rc stray
  shift 2
  export STUB_CALLS="$work/$name.calls"
  : >"$STUB_CALLS"
  mkdir -p "$work/home"
  out="$(env -i HOME="$work/home" PATH="$work/bin:/usr/bin:/bin" STUB_CALLS="$STUB_CALLS" SESSION_CONFIRM=yes AWS_PROFILE=stub \
    EGRESS_CIDR=192.0.2.1/32 EXDIR="$work/$name" TRAIN=restart RESTART_STAGE=smoke TRAIN_AZ=ap-northeast-2a APPROVED_TRAIN_SHA256="$sha" TTL_MINUTES=300 "$@" \
    timeout 60 bash "$repo/hack/eks-gitops-session.sh" 2>&1)"
  rc=$?
  # A watchdog would be a detached process naming this case's directory; one left alive would fire at its TTL.
  stray="$(pgrep -f -- "$work/$name/" | paste -sd' ')"
  if [[ -n "$stray" ]]; then
    # shellcheck disable=SC2086
    kill $stray
    bad "$name: left a watchdog running (pid $stray), stopped by the test"
    return
  fi
  if ((rc == 0)); then
    bad "$name: the session exited 0"
  # Judged on the line the session died with, not anywhere in its output: a refusal that only logs its reason and goes
  # on prints the same words, and passed this check until a mutation showed it.
  elif [[ "$want" != - && "$(grep 'FATAL' <<<"$out" | tail -1)" != *"$want"* ]]; then
    bad "$name: the session did not die with '$want': $(grep 'FATAL' <<<"$out" | tail -1 | cut -c1-200)"
  elif [[ ! -s "$work/$name/session.log" ]]; then
    bad "$name: the session wrote no log, so nothing shows where it stopped"
  elif grep -q 'terraform init\|TTL kill switch armed' "$work/$name/session.log"; then
    bad "$name: the session went past its refusals: $(grep 'terraform init\|TTL kill switch armed' "$work/$name/session.log" | head -1)"
  elif [[ "$want" == - ]]; then
    ok "$name: stopped before Terraform at: $(tail -1 <<<"$out" | cut -c1-150)"
  else
    ok "$name: $(grep -oF "$want" <<<"$out" | head -1 | cut -c1-150)"
  fi
}

session "no zone" "TRAIN=restart is registered in ap-northeast-2a" TRAIN_AZ=
session "another zone" "TRAIN=restart is registered in ap-northeast-2a, and TRAIN_AZ is 'ap-northeast-2c'" TRAIN_AZ=ap-northeast-2c
session "no approved hash" "needs APPROVED_TRAIN_SHA256" APPROVED_TRAIN_SHA256=
session "another train.py" "not the approved" APPROVED_TRAIN_SHA256="$(printf '%064d' 0)"
session "no stage" "TRAIN=restart needs RESTART_STAGE=smoke, run and inspected first, or RESTART_STAGE=full" RESTART_STAGE=
session "an unknown stage" "RESTART_STAGE is 'all', not smoke or full" RESTART_STAGE=all
session "a deadline too short" "with RESTART_STAGE=smoke needs TTL_MINUTES of at least 288 for its waits; it is 280" TTL_MINUTES=280
# A deadline the stage needs, and more than a fresh credential can cover with the destroy after it.
session "a deadline past the credential limit" "TTL_MINUTES=670 and the 40-minute destroy need 710 min of credential, more than the 700" TTL_MINUTES=670
# The refusal's own words, not "expires in", which the line a passing credential prints contains too.
session "a credential expiring first" "and the session needs 340; authenticate again first" STUB_CRED_MIN=300
# One minute short of the longest deadline a fresh credential allows: the check reads whole minutes left, rounded down.
session "a credential a minute short" "expires in 698 minutes and the session needs 700" STUB_CRED_MIN=699 TTL_MINUTES=660
session "a credential with no expiry" "carries no expiry" STUB_CRED_NOEXP=1
session "the quota short" "plus 12 is above the quota of 8" STUB_QUOTA=8
# Three g5.12xlarge another session left running hold 144 of the 128, so the twelve this one asks for cannot fit.
session "the quota used by others" "plus 12 is above the quota of 128" \
  STUB_RUNNING='[["i-0123456789abcdef0", "g5.12xlarge", null], ["i-0123456789abcdef1", "g5.12xlarge", null], ["i-0123456789abcdef2", "g5.12xlarge", null]]'
session "the price over the ceiling" "above the ceiling of \$1.40" STUB_PRICE=1.5000000000
session "with SERVE" "would buy GPUs in two groups" SERVE=yes
touch "$repo/stray-edit"
session "a dirty tree" "uncommitted change(s), and the run's provenance is a commit"
rm -f "$repo/stray-edit"
# Every refusal passed: the next stop is the destroy-window check or the stub gh, both before the kill switch.
session "every refusal passed" -
log="$work/every refusal passed/session.log"
if grep -q 'terraform variables for every apply and destroy: .*-var=gpu_max_nodes=3 -var=gpu_availability_zone=ap-northeast-2a -var=efs_enabled=true' "$log"; then
  ok "the restart variables the watchdog's destroy is built from were logged: $(grep -o 'gpu_max_nodes=3.*' "$log")"
else
  bad "no restart terraform variables in the log of the run that passed every refusal: $(grep 'terraform variables' "$log")"
fi
for want in "credential expires in" "fits the quota of 128" "On-Demand in ap-northeast-2 at \$1.237" "RESTART_STAGE=smoke: TTL_MINUTES 300 covers its 288" \
  "GPU budget 12480s"; do
  if grep -qF "$want" "$log"; then ok "the passing run logged '$want'"; else bad "the passing run did not log '$want'"; fi
done
# The full stage at its fixed repetitions, and the longest deadline, each pass a fresh 720-minute credential.
# passes NAME WANT [VAR=VALUE...]: the session got past every refusal before the destroy check and logged WANT.
passes() {
  local name="$1" want="$2"
  shift 2
  session "$name" - "$@"
  if grep -qF "$want" "$work/$name/session.log"; then ok "$name: logged '$want'"; else bad "$name: did not log '$want': $(grep -F 'RESTART_STAGE' "$work/$name/session.log" | tail -1)"; fi
}
passes "the full stage" "RESTART_STAGE=full: TTL_MINUTES 524 covers its 524" RESTART_STAGE=full TTL_MINUTES=524
passes "the longest deadline" "the credential expires in 719 minutes, at least the 700" TTL_MINUTES=660

# --- 2. the library's functions ------------------------------------------------------------------------------------
# lib CASE SCRIPT: runs SCRIPT in a fresh shell with the library sourced, the stubs first on PATH, and the rules of
# $work/rules/CASE/; its output is the case's, and the stubs' calls go to $work/CASE.calls.
lib() {
  local name="$1" script="$2"
  mkdir -p "$work/rules/$name" "$work/out/$name"
  STUB_CALLS="$work/$name.calls" STUB_RULES="$work/rules/$name" PATH="$work/bin:$PATH" RESTART_POLL=0 \
    RESTART_CONTEXT=stub RESTART_REGION=ap-northeast-2 RESTART_CLUSTER=gpu-platform RESTART_GROUP=gpu RESTART_NS=train-a \
    RESTART_QUEUE=gpu-train-a RESTART_SYS=gpu-platform-control-plane-system RESTART_OUT="$work/out/$name" \
    bash -c ". hack/lib/train-session.sh; . hack/lib/gpu-ttl.sh; . hack/lib/gpu-fault.sh; . hack/lib/restart-session.sh; $script" 2>&1
}

# The termination fences only on EC2's own `terminated`: shutting-down, then an unreadable answer, then terminated.
mkdir -p "$work/rules/fence"
cat >"$work/rules/fence/aws.sh" <<'EOF'
case "$*" in
  "ec2 terminate-instances"*) echo "TERMINATINGINSTANCES" ;;
  "ec2 describe-instances"*)
    n=$(grep -c 'describe-instances' "$STUB_CALLS")
    case "$n" in 1) echo shutting-down ;; 2) echo "throttled" >&2; exit 255 ;; *) echo terminated ;; esac ;;
esac
EOF
out="$(lib fence 'restart_terminate_and_fence i-0abc0123456789def ip-10-0-64-12 rst-t1 "$RESTART_OUT" 30')"
marks="$(python3 -c 'import json, sys; print(" ".join(json.loads(l)["mark"] for l in open(sys.argv[1])))' "$work/out/fence/marks.jsonl")"
annotations="$(grep -c 'annotate mltrainingjob rst-t1 platform.lkhun9311.github.io/fenced-nodes=ip-10-0-64-12' "$work/fence.calls")"
if [[ "$marks" == "fault-start fault-end terminated-read fenced" && "$annotations" == 1 && "$out" == *"fenced"* ]]; then
  ok "the node is fenced once, after EC2 said terminated: $marks"
else
  bad "the fencing order was '$marks' with $annotations annotation(s): $out"
fi
describes=$(grep -c 'describe-instances' "$work/fence.calls")
last_describe=$(grep -n 'describe-instances' "$work/fence.calls" | tail -1 | cut -d: -f1)
annotate_at=$(grep -n 'annotate' "$work/fence.calls" | cut -d: -f1)
if [[ "$describes" == 3 && -n "$annotate_at" && "$annotate_at" -gt "$last_describe" ]]; then
  ok "the annotation follows the third describe, the first to say terminated"
else
  bad "$describes describe(s) before the annotation, want 3: neither shutting-down nor an unreadable answer is off"
fi

mkdir -p "$work/rules/never"
cat >"$work/rules/never/aws.sh" <<'EOF'
case "$*" in "ec2 describe-instances"*) echo shutting-down ;; esac
EOF
out="$(lib never 'restart_terminate_and_fence i-0abc0123456789def ip-10-0-64-12 rst-t1 "$RESTART_OUT" 2; echo "rc=$?"')"
if [[ "$out" == *"not reported terminated"*"rc=1"* ]] && ! grep -q annotate "$work/never.calls"; then
  ok "an instance never reported terminated is never fenced"
else
  bad "the never-terminated case: $out; $(grep -c annotate "$work/never.calls") annotation(s)"
fi
mkdir -p "$work/rules/refused"
cat >"$work/rules/refused/aws.sh" <<'EOF'
case "$*" in "ec2 terminate-instances"*) echo "UnauthorizedOperation" >&2; exit 254 ;; esac
EOF
out="$(lib refused 'restart_terminate_and_fence i-0abc0123456789def ip-10-0-64-12 rst-t1 "$RESTART_OUT" 5; echo "rc=$?"')"
if [[ "$out" == *"terminate-instances on i-0abc0123456789def failed"*"rc=1"* ]] && ! grep -q 'describe-instances\|annotate' "$work/refused.calls"; then
  ok "a refused termination neither waits nor fences, and is marked fault-refused"
else
  bad "the refused termination: $out"
fi

# The job: no exec, a job ID of its own, NCCL to a per-attempt, per-rank file in a directory made first, the pinned image.
out="$(lib render 'restart_render_job rst-rank-kill-1 train-a gpu-train-a rst-rank-kill-1-0a1b2c3d rank-kill-1')"
body="$(python3 -c 'import json, sys; print(json.loads(sys.stdin.read())["spec"]["command"][2])' <<<"$out")"
spec="$(python3 -c '
import json, sys
s = json.loads(sys.stdin.read())["spec"]
print(s["image"], s["distributed"], s["stateVolume"], s["gpuClass"])' <<<"$out")"
for want in 'CKPT_JOB_ID=rst-rank-kill-1-0a1b2c3d' 'CKPT_BACKEND=nccl' 'CKPT_FAULT=kill-before-fsync:12:1' \
  'NCCL_DEBUG_FILE="$nccl_dir/a${TRAINING_ATTEMPT}-r${RANK}-%h.%p.log"' 'mkdir -p "$nccl_dir"' '|| exit 87' 'CKPT_COLLECTIVE_TIMEOUT=60'; do
  if grep -qF -- "$want" <<<"$body"; then ok "the job's command has $want"; else bad "the job's command lacks $want"; fi
done
if grep -qE '(^|[^a-z])exec ' <<<"$body"; then bad "the job's command execs, so the trainer would be PID 1"; else ok "the job's command never execs"; fi
if [[ "$(tail -1 <<<"$body")" == "python /tmp/train.py" ]]; then ok "the trainer is started as a child of the shell"; else bad "the last line is '$(tail -1 <<<"$body")'"; fi
want_spec="docker.io/pytorch/pytorch@sha256:c8268a92a69bd500f8be0e665b2630ee006dadaf7bfbc24249141b15ff622755 {'worldSize': 2, 'maxRestarts': 1} {'claimName': 'restart-shared', 'mountPath': '/state'} a10g"
if [[ "$spec" == "$want_spec" ]]; then ok "the job's spec is the registered one"; else bad "the job's spec is '$spec'"; fi
decoded="$(sed -n 's/^echo \([A-Za-z0-9+\/=]*\) | base64 -d >\/tmp\/train.py$/\1/p' <<<"$body" | base64 -d | sha256sum | cut -d' ' -f1)"
if [[ "$decoded" == "$sha" ]]; then ok "the carried trainer is the committed train.py"; else bad "the carried trainer hashes to $decoded"; fi
out="$(lib render2 'restart_render_job x train-a gpu-train-a x-1 fsdp-1; echo "rc=$?"')"
if [[ "$out" == *"not a registered case"*"rc=1" ]]; then ok "an unregistered case is refused"; else bad "an unregistered case: $out"; fi
out="$(lib cases 'RESTART_STAGE=smoke restart_cases | paste -sd" "; RESTART_STAGE=full restart_cases | paste -sd" "; RESTART_STAGE= restart_cases; echo "rc=$?"')"
want_cases="reference no-rng-control dcgm-1 terminate-wait-1"$'\n'"reference no-rng-control rank-kill-1 rank-kill-2 dcgm-1 dcgm-2 terminate-spare-1 terminate-spare-2 terminate-wait-1 terminate-wait-2"
if [[ "$out" == "$want_cases"$'\n'*"not smoke or full"*"rc=1" ]]; then ok "smoke's four cases, full's ten in the registered order, and no stage refused"; else bad "the cases: $out"; fi

# The budget is the sum of the enforced shares: preparation 4,080 s, each slot its pre share, 1,380 s of submission,
# run, evidence, retirement and files, 180 s more for a DCGM reset, and 900 s of scale-down.
budget() {
  lib budget "WAIT_GPU_NODE=900 WAIT_GPU_PLUGIN=600 WAIT_QUAL_RUN=1500 WAIT_GPU_GONE=600; $1"
}
out="$(budget 'RESTART_STAGE=smoke; prev=; for c in $(restart_cases); do printf "%s=%s " $c $(restart_slot_seconds $c "$prev"); prev=$c; done; restart_gpu_budget')"
if [[ "$out" == "reference=1680 no-rng-control=1680 dcgm-1=1860 terminate-wait-1=2280 12480" ]]; then
  ok "smoke's slots and its GPU budget: $out"
else
  bad "smoke's slots: $out"
fi
out="$(budget 'RESTART_STAGE=full; restart_gpu_budget; restart_ttl_refusal full 524 "$(restart_gpu_budget)" 1200; echo "rc=$?"')"
if [[ "$out" == "26640"$'\n'*"covers its 524"*"rc=0" ]]; then ok "full at its two repetitions fits: $(tail -2 <<<"$out" | head -1)"; else bad "full at two: $out"; fi
# The registered five, and three, are refused whatever TTL_MINUTES says, because no credential the account issues covers them.
for reps in 3:689:729 5:1019:1059; do
  out="$(budget "RESTART_STAGE=full RESTART_REPS=${reps%%:*}; restart_ttl_refusal full 660 \"\$(restart_gpu_budget)\" 1200; echo \"rc=\$?\"")"
  want="needs TTL_MINUTES of at least $(cut -d: -f2 <<<"$reps"), and with the 40-minute destroy ${reps##*:} min of credential"
  if [[ "$out" == *"$want"*"cannot run as one session"*"rc=1" ]]; then ok "full at ${reps%%:*} repetitions is refused: $want"; else bad "full at ${reps%%:*}: $out"; fi
done

# The first nodes are warmed in parallel under one deadline: every warm-up Pod is created before the first wait, and
# each wait is given what is left of the one deadline, not a budget of its own.
mkdir -p "$work/rules/warm" "$work/out/warm"
cat >"$work/rules/warm/kubectl.sh" <<'EOF'
case "$*" in
  *"get nodes"*) printf 'node-a\nnode-b\nnode-c\n' ;;
  *" wait "*) sleep 1 ;;
esac
EOF
: >"$work/out/warm/warmed.txt"
out="$(lib warm 'restart_prepare_nodes "$RESTART_OUT/warmed.txt" $((SECONDS + 30)); echo "rc=$?"')"
last_create="$(grep -n 'apply -f -' "$work/warm.calls" | tail -1 | cut -d: -f1)"
first_wait="$(grep -n ' wait ' "$work/warm.calls" | head -1 | cut -d: -f1)"
timeouts="$(grep -oE -- '--timeout=[0-9]+s' "$work/warm.calls" | paste -sd' ')"
if [[ "$out" == *"rc=0" && "$last_create" -lt "$first_wait" && "$timeouts" =~ ^--timeout=(30|29)s\ --timeout=(29|28)s\ --timeout=(28|27)s$ &&
  "$(paste -sd' ' "$work/out/warm/warmed.txt")" == "node-a node-b node-c" ]]; then
  ok "three warm-ups started before the first wait, each wait the rest of one deadline: $timeouts"
else
  bad "the parallel warm-up: $out; create at $last_create, first wait at $first_wait, $timeouts"
fi

# A failed read of the taints is not "no node tainted".
mkdir -p "$work/rules/taints"
cat >"$work/rules/taints/kubectl.sh" <<'EOF'
case "$*" in
  *"jsonpath"*"taints"*) echo "Unable to connect to the server" >&2; exit 1 ;;
  *"get nodes"*"-o name"*) printf 'node/a\nnode/b\n' ;;
  *"get nodes -l eks.amazonaws.com/nodegroup=gpu -o json"*)
    echo '{"items": [{"metadata": {"name": "a"}, "spec": {"providerID": "aws:///x/i-0a"}, "status": {"conditions": [{"type": "Ready", "status": "True"}], "allocatable": {"nvidia.com/gpu": "1"}}},
                     {"metadata": {"name": "b"}, "spec": {"providerID": "aws:///x/i-0b"}, "status": {"conditions": [{"type": "Ready", "status": "True"}], "allocatable": {"nvidia.com/gpu": "1"}}}]}' ;;
  *"get pods -A -l app.kubernetes.io/component=nvidia-device-plugin"*)
    echo '{"items": [{"spec": {"nodeName": "a"}, "status": {"conditions": [{"type": "Ready", "status": "True"}]}}, {"spec": {"nodeName": "b"}, "status": {"conditions": [{"type": "Ready", "status": "True"}]}}]}' ;;
esac
EOF
out="$(lib taints 'RESTART_INSTANCES_FILE="$RESTART_OUT/instances"; TRAIN_POLL=0; restart_wait_group 2 5; echo "rc=$?"')"
if [[ "$out" == *"could not read the GPU nodes' taints"*"rc=1" ]]; then ok "an unreadable taint list refuses the group"; else bad "the unreadable taints: $out"; fi
out="$(lib volume 'restart_render_volume "" train-a; echo "rc=$?"; restart_render_volume fs-0123456789abcdef0 train-a | grep -c "volumeHandle: fs-0123456789abcdef0\|ReadWriteMany"')"
if [[ "$out" == *"is not one"*"rc=1"*"3" ]]; then ok "the volume refuses an empty file system ID and renders a RWX volume naming it"; else bad "the volume: $out"; fi

