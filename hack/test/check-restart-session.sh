chmod +x "$work/bin/stub"
for t in aws terraform kubectl helm gh; do ln -s stub "$work/bin/$t"; done
# The UTC hour and minute the destroy window is judged at, when STUB_UTC_HM names them; every other date is the real one.
cat >"$work/bin/date" <<'EOF'
#!/usr/bin/env bash
if [[ -n "${STUB_UTC_HM:-}" && "$*" == "-u +%H" ]]; then echo "${STUB_UTC_HM%:*}"; exit 0; fi
if [[ -n "${STUB_UTC_HM:-}" && "$*" == "-u +%M" ]]; then echo "${STUB_UTC_HM#*:}"; exit 0; fi
# With STUB_UUTILS_NS the nanoseconds are fixed and a width-limited %6N or %3N prints them as uutils date 0.8.0 does, the
# whole count with its leading zeros dropped, so .001229623 came out as .1229623 on the host that runs the paid session.
if [[ -n "${STUB_UUTILS_NS:-}" && "${1:-}" == -u && "${2:-}" == +* ]]; then
  fmt="${2#+}"
  fmt="${fmt//%6N/$((10#$STUB_UUTILS_NS))}"
  fmt="${fmt//%3N/$((10#$STUB_UUTILS_NS))}"
  exec /usr/bin/date -u "+${fmt//%N/$STUB_UUTILS_NS}"
fi
exec /usr/bin/date "$@"
EOF
chmod +x "$work/bin/date"

# --- 1. the session's refusals ------------------------------------------------------------------------------------
# A copy holding only what the session reads before Terraform, committed, because a dirty tree is one of the refusals;
# it has no bin/, which the session puts ahead of PATH and which would otherwise answer in the stubs' place.
repo="$work/repo"
mkdir -p "$repo/hack/lib" "$repo/experiments/distributed-restart" "$repo/experiments/cpu-ddp" "$repo/experiments/multi-gpu-throughput"
cp hack/eks-gitops-session.sh "$repo/hack/"
