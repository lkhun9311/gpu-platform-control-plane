#!/usr/bin/env bash
#
# The distributed restart paid session (TRAIN=restart), rehearsed with no cluster, no card and no credentials.
#
#   bash hack/test/check-restart-session.sh
#
# Three parts, each against the real files:
#   1. hack/eks-gitops-session.sh with TRAIN=restart, run from a throwaway commit of what it reads, against stub aws,
#      terraform, kubectl, helm and gh: every refusal stops it before `terraform init` and before the kill switch, and
#      a run that passes every refusal has logged the terraform variables the watchdog's destroy is built from; the
#      stages' deadlines against a credential of at most 720 minutes, and the nightly destroy's window.
#   2. hack/lib/restart-session.sh's functions against stubs answering from per-case scripts: the termination fences
#      only on EC2's `terminated`, the job and volume it renders, the fault window and its last read before a fault,
#      the clock probe, the retirement that does not read an error as "gone", the GPU deadline, the budget's shares,
#      the parallel warm-up, the fault path's readiness, and restart_run with one case run for real against stubs.
#   3. experiments/distributed-restart/score_eks.py over runs generated by hack/test/restart-session/make_fixture.py
#      from the producers' own line shapes: a clean run is accepted, and each defect is refused with its reason.
#
# What this does not show: the case procedure (restart_run_case) against a cluster, controller, NFS or GPU; its paths
# here run against stubs whose answers were written for them, not taken from a cluster.
set -uo pipefail
self="$(readlink -f "$0")"
