d = pathlib.Path(sys.argv[1]) / "no-rng-control"
ref = [json.loads(l) for f in (pathlib.Path(sys.argv[1]) / "reference").glob("log-*") for l in open(f)]
params = next(r["params"] for r in ref if r.get("params"))
for f in d.glob("log-*"):
    rows = [json.loads(l) for l in open(f)]
    open(f, "w").write("".join(json.dumps({**r, "params": params} if r.get("params") else r) + "\n" for r in rows))' "$work/run-blind"
line="$(python3 experiments/distributed-restart/score_eks.py "$work/run-blind" | grep '^[A-Z]* *no-rng-control')"
if [[ "$line" == FAILED*"dropping the RNG left the parameters within"* ]]; then ok "a control equal to the reference is FAILED"; else bad "the blind control: $line"; fi
for refusal in dirty:"uncommitted change" unapproved:"is not the approved"; do
  run="$work/run-${refusal%%:*}"
  python3 hack/test/restart-session/make_fixture.py "$run" "${refusal%%:*}" reference
  out="$(python3 experiments/distributed-restart/score_eks.py "$run" 2>&1)"
  rc=$?
  if [[ $rc == 2 && "$out" == *"REFUSED"*"${refusal#*:}"* ]]; then ok "${refusal%%:*}: the run is refused, exit 2"; else bad "${refusal%%:*}: exit $rc, $out"; fi
done
# A run still in progress scores what exists, and a case the runner chose not to start is NOTRUN, not missing.
run="$work/run-partial"
python3 hack/test/restart-session/make_fixture.py "$run"
rm -rf "$run"/terminate-wait-*
mkdir "$run/terminate-wait-1" && echo "the GPU deadline is 9 min away" >"$run/terminate-wait-1/NOTRUN"
out="$(python3 experiments/distributed-restart/score_eks.py --partial "$run" 2>&1)"
if [[ "$out" == *"NOTRUN   terminate-wait-1: the GPU deadline"* && "$out" != *"terminate-wait-2"* && "$out" == *"1 NOTRUN"* ]]; then
  ok "--partial scores what exists and reports a case not started as NOTRUN"
else
  bad "the partial run: $(grep terminate-wait <<<"$out" | head -3)"
fi
out="$(python3 experiments/distributed-restart/score_eks.py "$run" 2>&1)"
if [[ "$out" == *"VOID     terminate-wait-2: its directory is missing"* ]]; then ok "without --partial a registered case with no directory is VOID"; else bad "the full score of a partial run: $(grep terminate-wait-2 <<<"$out")"; fi

if ((fails > 0)); then
  echo "check-restart-session: $fails failure(s)"
  exit 1
fi
echo "check-restart-session: all checks passed"
