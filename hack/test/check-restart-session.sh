# session NAME WANT [VAR=VALUE...]: TRAIN=restart with the given environment exits non-zero, prints WANT, and never
# reached Terraform or the kill switch.
session() {
  local name="$1" want="$2" out rc stray
  shift 2
  export STUB_CALLS="$work/$name.calls"
  : >"$STUB_CALLS"
  mkdir -p "$work/home"
  out="$(env -i HOME="$work/home" PATH="$work/bin:/usr/bin:/bin" STUB_CALLS="$STUB_CALLS" SESSION_CONFIRM=yes AWS_PROFILE=stub \
    EGRESS_CIDR=192.0.2.1/32 EXDIR="$work/$name" TRAIN=restart RESTART_STAGE=smoke TRAIN_AZ=ap-northeast-2a APPROVED_TRAIN_SHA256="$sha" TTL_MINUTES=300 "$@" \
    timeout 60 bash "$repo/hack/eks-gitops-session.sh" 2>&1)"
  rc=$?
  # A watchdog would be a detached process naming its pid file under this run's directory; one left alive would fire at
  # its TTL.
  # The case's name is not matched: the watchdog's command quotes it, a space becoming '\ ', so two watchdogs of cases
  # named with spaces outlived a mutation run unseen.
  stray="$(pgrep -f -- "KILL_PIDFILE=$work/" | paste -sd' ')"
  if [[ -n "$stray" ]]; then
    # shellcheck disable=SC2086
    kill $stray
    bad "$name: left a watchdog running (pid $stray), stopped by the test"
    return
  fi
  if ((rc == 0)); then
    bad "$name: the session exited 0"
  # Judged on the line the session died with, not anywhere in its output: a refusal that only logs its reason and goes
  # on prints the same words, and passed this check until a mutation showed it.
  elif [[ "$want" != - && "$(grep 'FATAL' <<<"$out" | tail -1)" != *"$want"* ]]; then
    bad "$name: the session did not die with '$want': $(grep 'FATAL' <<<"$out" | tail -1 | cut -c1-200)"
  elif [[ ! -s "$work/$name/session.log" ]]; then
    bad "$name: the session wrote no log, so nothing shows where it stopped"
  elif grep -q 'terraform init\|TTL kill switch armed' "$work/$name/session.log"; then
    bad "$name: the session went past its refusals: $(grep 'terraform init\|TTL kill switch armed' "$work/$name/session.log" | head -1)"
  elif [[ "$want" == - ]]; then
    ok "$name: stopped before Terraform at: $(tail -1 <<<"$out" | cut -c1-150)"
  else
    ok "$name: $(grep -oF "$want" <<<"$out" | head -1 | cut -c1-150)"
  fi
}

