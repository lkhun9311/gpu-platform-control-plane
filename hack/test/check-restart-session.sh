  if [[ -n "${STUB_RULES:-}" && -f "$STUB_RULES/kubeconfig.delay" ]]; then sleep "$(cat "$STUB_RULES/kubeconfig.delay")"; fi
  if [[ -n "${STUB_RULES:-}" && -f "$STUB_RULES/kubeconfig.json" ]]; then cat "$STUB_RULES/kubeconfig.json"; else
