#!/usr/bin/env bash
# Step 3: drain does not kill a running job; a node that stops answering does, and a requeue-able job is requeued; scontrol requeue does the same by hand.
source "$(dirname "$0")/lib.sh"

Q="squeue -o '%.6i %.10j %.8u %.3t %.10M %.12b %N %R'"

out 03a-drain.txt
at slurmctld -u bob "sbatch -J on-c2 -w c2 --gres=gpu:1 --wrap 'sleep 60'"
wait_until 30 "squeue -h -n on-c2 -t R | grep -q ."
at slurmctld "$Q"
note "Drain c2 while its job runs."
at slurmctld "scontrol update nodename=c2 state=drain reason='lab: drain while a job runs'"
at slurmctld "sinfo -N -o '%N %T %G %E'"
at slurmctld "$Q"
note "A job that names c2 cannot start there; an unpinned 2-GPU job goes elsewhere."
at slurmctld -u bob "sbatch -J wants-c2 -w c2 --gres=gpu:1 --wrap 'sleep 30'"
at slurmctld -u bob "sbatch -J anywhere --gres=gpu:2 --wrap 'sleep 30'"
wait_until 30 "squeue -h -n anywhere -t R | grep -q ."
at slurmctld "$Q"
note "The running job is left to finish; c2 moves from draining to drained only when it has."
trace 120 "! squeue -h -n on-c2 | grep -q ." "sinfo -h -n c2 -o '%T'; scontrol show node c2 | grep -oE 'State=[^ ]+'; squeue -h -n on-c2 -o '%i %T'"
at slurmctld "sinfo -N -o '%N %T %G %E'"
at slurmctld "scontrol show node c2 | grep -E 'State=|Reason='"
at slurmctld "sacct -X -n -j \$(sacct -X -n -P -o JobID,JobName | grep '|on-c2\$' | cut -d'|' -f1) -o JobID,JobName,State,ExitCode,Start,End,NodeList"
at slurmctld "$Q"
at slurmctld "scontrol update nodename=c2 state=resume"
wait_until 30 "squeue -h -n wants-c2 -t R,CD | grep -q . || sacct -X -n -P -o JobName,State | grep -q '^wants-c2|COMPLETED'"
at slurmctld "sinfo -N -o '%N %T %G %E'"
at slurmctld "$Q"
at slurmctld "scancel -u bob"
wait_until 30 "[ -z \"\$(squeue -h)\" ]"

out 03b-node-down.txt
note "c1 and c2 are held briefly so the two test jobs land on c3; then the holders end and c1 and c2 are free."
at slurmctld -u bob "sbatch -J hold-1 -w c1 --gres=gpu:2 --wrap 'sleep 900'"
at slurmctld -u bob "sbatch -J hold-2 -w c2 --gres=gpu:2 --wrap 'sleep 900'"
wait_until 30 "[ \$(squeue -h -u bob -t R | wc -l) -eq 2 ]"
at slurmctld -u alice "sbatch -J rq-yes --requeue --open-mode=append --gres=gpu:1 --wrap 'echo start \$(date -u +%T) on \$(hostname) restart=\${SLURM_RESTART_COUNT:-0}; sleep 900'"
at slurmctld -u alice "sbatch -J rq-no --no-requeue --gres=gpu:1 --wrap 'sleep 900'"
wait_until 30 "[ \$(squeue -h -u alice -t R | wc -l) -eq 2 ]"
at slurmctld -u bob "scancel -n hold-1; scancel -n hold-2"
wait_until 30 "[ -z \"\$(squeue -h -u bob)\" ]"
at slurmctld "$Q"
note "Stop c3's container: its slurmd and the job processes on it end without a word to slurmctld."
host "docker compose stop -t 0 c3"
trace 180 "squeue -h -n rq-yes -t R -o %N | grep -qv c3" "sinfo -h -n c3 -o '%T %E'; squeue -h -u alice -o '%i %j %T %r %N'"
at slurmctld "sinfo -N -o '%N %T %E'"
at slurmctld "scontrol show job \$(squeue -h -n rq-yes -o %i) | grep -E 'JobState|Requeue|Restarts|SubmitTime|EligibleTime|StartTime|NodeList='"
at slurmctld "sacct -D -n -u alice -S now-10minutes -o JobID,JobName,State,ExitCode,Start,End,NodeList | grep -E 'rq-'"
at slurmctld "grep -hE 'c3|NODE_FAIL|Requeu' /var/log/slurm/slurmctld.log | grep -vE 'debug' | tail -15"
node=$(docker compose exec -T slurmctld squeue -h -n rq-yes -o %N)
id=$(docker compose exec -T slurmctld squeue -h -n rq-yes -o %i)
note "Output of the requeued job's second run, on ${node:-none}; nothing is shared between nodes, so the first run's output is on c3's disk."
at "${node:-c1}" "cat /home/alice/slurm-${id:-0}.out"

note "Bring c3 back; ReturnToService=1 returns a node that was DOWN only for not responding."
host "docker compose start c3"
wait_until 60 "sinfo -h -n c3 -o %T | grep -qE 'idle|mixed'"
at slurmctld "sinfo -N -o '%N %T %E'"
note "The first run's output, still on c3's disk because the container was stopped, not removed."
at c3 "cat /home/alice/slurm-${id:-0}.out"

out 03c-scontrol-requeue.txt
note "The same requeue by hand, on the job from 03b once it is running again."
wait_until 60 "squeue -h -n rq-yes -t R | grep -q ."
at slurmctld "$Q"
at slurmctld "scontrol requeue \$(squeue -h -n rq-yes -o %i)"
at slurmctld "$Q"
at slurmctld "scontrol show job \$(squeue -h -n rq-yes -o %i) | grep -E 'JobState|Reason|Requeue|Restarts|EligibleTime|StartTime'"
trace 180 "squeue -h -n rq-yes -t R | grep -q ." "squeue -h -n rq-yes -o '%i %T %r %N'"
at slurmctld "scontrol show job \$(squeue -h -n rq-yes -o %i) | grep -E 'JobState|Restarts|StartTime'"
note "scontrol requeue on a --no-requeue job, for contrast."
at slurmctld -u alice "sbatch -J rq-no-2 --no-requeue --gres=gpu:1 --wrap 'sleep 900'"
wait_until 30 "squeue -h -n rq-no-2 -t R | grep -q ."
at slurmctld "scontrol requeue \$(squeue -h -n rq-no-2 -o %i)"
at slurmctld "$Q"
at slurmctld "scancel -u alice; scancel -u bob"
wait_until 30 "[ -z \"\$(squeue -h)\" ]"
